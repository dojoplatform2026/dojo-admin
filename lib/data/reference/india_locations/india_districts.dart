/// Returns all districts belonging to a state/UT LGD code.
List<IndiaDistrict> districtsForState(String stateCode) {
  return indiaDistricts
      .where((district) => district.stateCode == stateCode)
      .toList(growable: false);
}

/// Finds a district using its LGD district code.
IndiaDistrict? districtByCode(String districtCode) {
  for (final district in indiaDistricts) {
    if (district.districtCode == districtCode) return district;
  }
  return null;
}

/// Case-insensitive English-name search, optionally limited to a state.
List<IndiaDistrict> searchIndiaDistricts(
  String query, {
  String? stateCode,
}) {
  final normalizedQuery = query.trim().toLowerCase();
  if (normalizedQuery.isEmpty) return const <IndiaDistrict>[];
  return indiaDistricts.where((district) {
    final matchesState = stateCode == null || district.stateCode == stateCode;
    final matchesName = district.districtName.toLowerCase().contains(normalizedQuery) ||
        district.districtNameLocal.toLowerCase().contains(normalizedQuery);
    return matchesState && matchesName;
  }).toList(growable: false);
}
